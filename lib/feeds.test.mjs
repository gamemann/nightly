// Run: node --test lib/feeds.test.mjs
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { add, list, deploy, setBudget, summary, kindOf } from './feeds.mjs'
import { memDb } from './testdb.mjs'

test('releases: unique per repo/version/channel, rollback pointer defaults to the previous version, deploys move the environment marker', () => {
    const db = memDb()
    add(db, 'release', { repo: 'r', version: '1.0.0', ci: 'passing', changelog: 'first', at: '2026-01-01' })
    add(db, 'release', { repo: 'r', version: '1.1.0', ci: 'pending', at: '2026-02-01' })
    add(db, 'release', { repo: 'r', version: '1.1.0', ci: 'passing' })
    const rows = list(db, 'releases')
    assert.equal(rows.length, 2)
    assert.deepEqual([rows[0].version, rows[0].rollback, rows[0].ci], ['1.1.0', '1.0.0', 'passing'])
    deploy(db, { repo: 'r', version: '1.0.0', to: 'prod' })
    deploy(db, { repo: 'r', version: '1.1.0', to: 'prod' })
    const d = Object.fromEntries(list(db, 'release').map((r) => [r.version, r.deployedTo]))
    assert.deepEqual(d, { '1.0.0': '', '1.1.0': 'prod' })
    assert.throws(() => add(db, 'release', { repo: 'r', version: 'x', ci: 'bogus' }), /ci must be one of/)
})
test('crashes group by signature/version/platform and count up; a fixed one reopens', () => {
    const db = memDb()
    add(db, 'crash', { game: 'g', signature: 'null deref in foo', version: '1', platform: 'web' })
    add(db, 'crash', { game: 'g', signature: 'null deref in foo', version: '1', platform: 'web', count: 4 })
    add(db, 'crash', { game: 'g', signature: 'null deref in foo', version: '2', platform: 'web' })
    const rows = list(db, 'crash')
    assert.equal(rows.length, 2)
    assert.equal(rows.find((r) => r.version === '1').count, 5)
    assert.deepEqual(summary(db, 'crash', 'g').map((r) => [r.version, r.crashes]), [['1', 5], ['2', 1]])
    db.prepare("UPDATE CrashGroup SET status='fixed'").run()
    add(db, 'crash', { game: 'g', signature: 'null deref in foo', version: '1', platform: 'web' })
    assert.equal(list(db, 'crash', { status: 'open' }).length, 1)
})
test('web: a sample over its budget opens a finding, a passing one closes it', () => {
    const db = memDb()
    setBudget(db, 'g', 'bundle_kb', 500, 'kb')
    assert.equal(add(db, 'web', { game: 'g', metric: 'bundle_kb', value: 620, at: '2026-01-01' }).raised, 1)
    assert.equal(db.prepare("SELECT COUNT(*) n FROM RsiFinding WHERE domain='web' AND status='open'").get().n, 1)
    assert.equal(add(db, 'web', { game: 'g', metric: 'bundle_kb', value: 480, at: '2026-01-02' }).closed, 1)
    assert.equal(add(db, 'web', { game: 'g', metric: 'lcp_ms', value: 2000 }).raised, undefined)   // no budget, no finding
    assert.deepEqual(summary(db, 'web').map((r) => [r.metric, r.value, r.max]), [['bundle_kb', 480, 500], ['lcp_ms', 2000, null]])
    assert.throws(() => add(db, 'web', { game: 'g', metric: 'x', value: 'abc' }), /number/)
})
test('playtest and content feeds', () => {
    const db = memDb()
    add(db, 'playtest', { game: 'g', build: 'b1', rating: 4, text: 'fun' })
    add(db, 'playtest', { game: 'g', build: 'b1', rating: 2 })
    assert.equal(summary(db, 'playtest')[0].avgRating, 3)
    const a = add(db, 'content', { game: 'g', category: 'weapon', name: 'ak', metric: 'dps', value: 300, min: 100, max: 250 })
    assert.equal(a.raised, 1)
    assert.equal(add(db, 'content', { game: 'g', category: 'weapon', name: 'ak', metric: 'dps', value: 200, min: 100, max: 250 }).closed, 1)
    assert.equal(list(db, 'content').length, 1)
    assert.throws(() => kindOf('nope'), /unknown feed/)
    assert.throws(() => add(db, 'playtest', { build: 'x' }), /game is required/)
})

test('edit and delete by id (the panel and the CLI share them)', async () => {
    const { edit, remove, removeBudget } = await import('./feeds.mjs')
    const db = memDb()
    const c = add(db, 'crash', { game: 'g', signature: 'sig', count: 3 })
    add(db, 'crash', { game: 'g', signature: 'sig', count: 2 })
    assert.equal(list(db, 'crash')[0].count, 5)
    edit(db, 'crash', c.id, { status: 'ignored' })
    const row = list(db, 'crash')[0]
    assert.deepEqual([row.status, row.count], ['ignored', 5])
    assert.throws(() => edit(db, 'crash', c.id, {}), /nothing to change/)
    assert.throws(() => edit(db, 'crash', c.id, { status: 'bogus' }), /one of/)
    remove(db, 'crash', c.id)
    assert.equal(list(db, 'crash').length, 0)
    assert.throws(() => remove(db, 'crash', c.id), /no crash/)
    const p = add(db, 'playtest', { game: 'g', text: 'a', rating: 3 })
    edit(db, 'playtest', p.id, { rating: 5 })
    assert.equal(list(db, 'playtest')[0].rating, 5)
    setBudget(db, 'g', 'lat', 100, 'ms')
    removeBudget(db, 'g', 'lat')
    assert.throws(() => removeBudget(db, 'g', 'lat'), /no budget/)
})
